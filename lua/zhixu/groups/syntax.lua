local M = {}

function M.get(p, opts)
  local c, e = p.core, p.extensions
  local function styled(color, style)
    return vim.tbl_extend("force", { fg = color }, opts.styles[style] or {})
  end
  local groups = {
    Comment = styled(c.comment, "comments"),
    Constant = { fg = c.identifier },
    String = { fg = c.string },
    Character = { link = "String" },
    Number = { fg = c.number },
    Float = { link = "Number" },
    Boolean = { fg = c.foreground },
    Identifier = styled(c.identifier, "variables"),
    Function = styled(e.function_call, "functions"),
    Statement = styled(c.keyword, "keywords"),
    Conditional = { link = "Statement" },
    Repeat = { link = "Statement" },
    Label = { link = "Statement" },
    Keyword = { link = "Statement" },
    Exception = { link = "Statement" },
    Operator = { fg = c.foreground },
    PreProc = { fg = c.modifier },
    Include = { link = "PreProc" },
    Define = { link = "PreProc" },
    PreCondit = { link = "PreProc" },
    Macro = { fg = c.macro },
    Type = { fg = c.type },
    StorageClass = { fg = c.modifier },
    Structure = { link = "Type" },
    Typedef = { link = "Type" },
    Special = { fg = c.macro },
    SpecialChar = { link = "String" },
    Tag = { fg = c.keyword },
    Delimiter = { fg = c.foreground },
    SpecialComment = { link = "Comment" },
    Debug = { fg = c.macro },
    Underlined = { fg = e.blue, underline = true },
    Ignore = { fg = e.foreground_disabled },
    Todo = { fg = c.macro },
    ["@variable"] = { link = "Identifier" },
    ["@variable.builtin"] = { link = "Number" },
    ["@variable.parameter"] = { link = "Identifier" },
    ["@variable.parameter.builtin"] = { link = "Identifier" },
    ["@variable.member"] = { link = "Identifier" },
    ["@property"] = { link = "Identifier" },
    ["@constant"] = { link = "Constant" },
    ["@constant.builtin"] = { link = "Boolean" },
    ["@constant.macro"] = { link = "Macro" },
    ["@module"] = { link = "Identifier" },
    ["@module.builtin"] = { link = "Identifier" },
    ["@label"] = { link = "Label" },
    ["@string"] = { link = "String" },
    ["@string.documentation"] = { link = "Comment" },
    ["@string.regexp"] = { link = "String" },
    ["@string.escape"] = { link = "String" },
    ["@string.special"] = { link = "String" },
    ["@string.special.symbol"] = { link = "String" },
    ["@string.special.path"] = { link = "String" },
    ["@string.special.url"] = { link = "String" },
    ["@character"] = { link = "Character" },
    ["@character.special"] = { link = "Character" },
    ["@boolean"] = { link = "Boolean" },
    ["@number"] = { link = "Number" },
    ["@number.float"] = { link = "Float" },
    ["@type"] = { link = "Type" },
    ["@type.builtin"] = { link = "Type" },
    ["@type.definition"] = { link = "Type" },
    ["@attribute"] = { link = "PreProc" },
    ["@attribute.builtin"] = { link = "PreProc" },
    -- Tree-sitter distinguishes declarations from calls; shared Vim/LSP groups do not.
    ["@function"] = styled(c.foreground, "functions"),
    ["@function.method"] = styled(c.foreground, "functions"),
    ["@function.call"] = { link = "Function" },
    ["@function.method.call"] = { link = "Function" },
    ["@function.builtin"] = { link = "Macro" },
    ["@function.macro"] = { link = "Macro" },
    ["@constructor"] = { link = "Type" },
    ["@operator"] = { link = "Operator" },
    ["@keyword"] = { link = "Keyword" },
    ["@keyword.modifier"] = { link = "PreProc" },
    ["@keyword.directive"] = { link = "PreProc" },
    ["@keyword.directive.define"] = { link = "PreProc" },
    ["@keyword.import"] = { link = "Include" },
    ["@keyword.operator"] = { link = "Keyword" },
    ["@punctuation.delimiter"] = { link = "Delimiter" },
    ["@punctuation.bracket"] = { link = "Delimiter" },
    ["@punctuation.special"] = { link = "Delimiter" },
    ["@comment"] = { link = "Comment" },
    ["@comment.documentation"] = { link = "Comment" },
    ["@comment.error"] = { fg = c.error },
    ["@comment.warning"] = { fg = c.keyword },
    ["@comment.todo"] = { link = "Todo" },
    ["@comment.note"] = { link = "Todo" },
    ["@markup"] = { fg = c.foreground },
    ["@markup.strong"] = { bold = true },
    ["@markup.italic"] = { italic = true },
    ["@markup.strikethrough"] = { strikethrough = true },
    ["@markup.underline"] = { underline = true },
    ["@markup.heading"] = { fg = c.secondary_heading },
    ["@markup.heading.1"] = { fg = c.keyword },
    ["@markup.quote"] = { fg = c.comment },
    ["@markup.math"] = { fg = c.number },
    ["@markup.link"] = { link = "Underlined" },
    ["@markup.link.label"] = { link = "Underlined" },
    ["@markup.link.url"] = { link = "Underlined" },
    ["@markup.raw"] = { link = "String" },
    ["@markup.list"] = { fg = c.keyword },
    ["@markup.list.checked"] = { fg = c.success },
    ["@markup.list.unchecked"] = { fg = c.ui_dim },
    ["@diff.plus"] = { link = "Added" },
    ["@diff.minus"] = { link = "Removed" },
    ["@diff.delta"] = { link = "Changed" },
    ["@tag"] = { link = "Tag" },
    ["@tag.builtin"] = { link = "Tag" },
    ["@tag.attribute"] = { link = "PreProc" },
    ["@tag.delimiter"] = { link = "Delimiter" },
    -- Keep Go's builtin types and explicit declarations distinct from calls.
    goType = { link = "Type" },
    goSignedInts = { link = "Type" },
    goUnsignedInts = { link = "Type" },
    goFloats = { link = "Type" },
    goComplexes = { link = "Type" },
    goBuiltins = { link = "Macro" },
    goBoolean = { link = "Boolean" },
    goDeclaration = { link = "Keyword" },
    goDeclType = { link = "Keyword" },
    goFunction = styled(c.foreground, "functions"),
    goFunctionCall = { link = "Function" },
    markdownCode = { link = "String" },
    markdownCodeBlock = { link = "String" },
    markdownCodeDelimiter = { link = "String" },
    markdownUrl = { link = "Underlined" },
    markdownLinkText = { link = "Underlined" },
    markdownHeadingDelimiter = { link = "Title" },
    markdownH1 = { link = "Title" },
  }
  for level = 2, 6 do
    groups["@markup.heading." .. level] = { fg = c.secondary_heading }
    groups["markdownH" .. level] = { fg = c.secondary_heading }
  end

  local semantic = {
    namespace = "@module",
    type = "Type",
    class = "Type",
    enum = "Type",
    interface = "Type",
    struct = "Type",
    typeParameter = "Type",
    parameter = "Identifier",
    variable = "Identifier",
    property = "Identifier",
    enumMember = "Identifier",
    event = "Identifier",
    ["function"] = "Function",
    method = "Function",
    macro = "Macro",
    keyword = "Keyword",
    modifier = "PreProc",
    comment = "Comment",
    string = "String",
    number = "Number",
    regexp = "String",
    operator = "Operator",
    decorator = "PreProc",
    boolean = "Boolean",
  }
  for token, target in pairs(semantic) do
    groups["@lsp.type." .. token] = { link = target }
  end
  groups["@lsp.typemod.variable.defaultLibrary"] = { link = "Number" }
  groups["@lsp.typemod.function.defaultLibrary"] = { link = "Macro" }
  groups["@lsp.typemod.method.defaultLibrary"] = { link = "Macro" }
  groups["@lsp.typemod.class.defaultLibrary"] = { link = "Type" }
  groups["@lsp.typemod.type.defaultLibrary"] = { link = "Type" }
  groups["@lsp.mod.deprecated"] = { strikethrough = true }
  -- Modifier-only highlights must not replace the underlying syntax color.
  for _, modifier in ipairs({
    "readonly",
    "static",
    "defaultLibrary",
    "declaration",
    "definition",
    "async",
  }) do
    groups["@lsp.mod." .. modifier] = {}
  end
  return groups
end

return M
